import type { SourceId } from "./sources";

export const LIBRARY_VERSION = "lib-2026.10.1";

/** adjacent: builds on current work. stretch: needs real learning or change. no-switch: alongside a current job. */
export type ChangeLevel = "adjacent" | "stretch" | "no-switch";

export interface Pathway {
  id: string;
  title: string;
  /** null = useful across many causes. */
  cause: Cause | null;
  mode: Mode;
  change: ChangeLevel;
  need: string;
  mechanism: string;
  /** Most important first. */
  capabilities: Capability[];
  motivations: Motivation[];
  /** Pathways that suit people with little room for a switch right now. */
  lowCommitment: boolean;
  /** Draws on any one of the listed capabilities rather than mainly the first. */
  generalist?: boolean;
  learning: "Low" | "Medium" | "High";
  assumptions: string[];
  constraints: string[];
  /** Evidence strength for the opportunity itself (Impact Compass §9). Not a probability of success. */
  evidence: "Low" | "Moderate" | "High";
  /** What this person might add that would otherwise be missing (counterfactual contribution, §7). */
  counterfactual: string;
  /** Practical requirements to check before committing. */
  requirements: string;
  /** What would cause us to revise or reject this hypothesis (§10). */
  reviseIf: string;
  /** A seven-day test (§13): hypothesis, action, effort, evidence and a decision rule. */
  experiment: { title: string; hypothesis: string; steps: string[]; effort: string; evidence: string; decisionRule: string };
  sources: SourceId[];
  resources: SourceId[];
}

