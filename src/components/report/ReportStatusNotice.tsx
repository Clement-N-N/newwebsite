"use client";

import type { Report } from "@/lib/engine/schema";
import type { ReportStatus } from "@/lib/state/AssessmentProvider";
import { SAMPLE_BY_ID } from "@/lib/fixtures/profiles";

/** States plainly how the results were produced. Never implies AI analysis that did not happen. */
export function ReportStatusNotice({
  report,
  status,
  sampleId,
  onDark = false,
}: {
  report: Report;
  status: ReportStatus;
  sampleId: string | null;
  onDark?: boolean;
}) {
  const muted = onDark ? "text-brand-on-primary-muted" : "text-brand-muted";
  const ai = status.state === "ready" ? status.ai : null;
  const fallbackError = status.state === "ready" ? status.error : undefined;

  let source: string;
  if (report.meta.narrative === "ai") {
    source = "Recommendations from Impact Start's rules-based engine. Wording assisted by Claude (Anthropic) and checked by the same validator.";
  } else if (ai?.status === "failed" || ai?.status === "rejected") {
    source = `Generated by Impact Start's rules-based engine. AI-assisted wording was unavailable (${ai.reason}), so none was used.`;
  } else {
    source = "Generated by Impact Start's rules-based engine from your answers. No AI was used.";
  }

  return (
    <div className="flex flex-col gap-2">
      {report.meta.sample && (
        <p className={`inline-flex self-start rounded-full px-3 py-1.5 text-sm font-semibold ${onDark ? "bg-white/10 text-brand-accent-on-dark" : "bg-brand-accent-soft text-brand-accent-text"}`}>
          Demonstration: these results belong to {SAMPLE_BY_ID[sampleId ?? ""]?.name ?? "a fictional sample participant"}, not a real person.
        </p>
      )}
      {fallbackError && (
        <p role="status" className={`rounded-lg px-3 py-2 text-sm ${onDark ? "bg-white/10" : "bg-brand-warning-soft text-brand-warning"}`}>
          {fallbackError}
        </p>
      )}
      <p className={`text-xs ${muted}`}>{source}</p>
    </div>
  );
}
